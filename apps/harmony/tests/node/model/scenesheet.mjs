// SceneSheetModel（M1-5）：排序 / 截断、导语、漏斗、条宽、检测频率、来源规则；MockEngine 上来源切换 + 漏斗。
const { SceneSheetModel, LedeKind } = await import('../.out/rt/app/SceneSheetModel.ts');
const { MockEngine } = await import('../.out/rt/engine/MockEngine.ts');
const { copySettings } = await import('../.out/rt/engine/Model.ts');
let bad=0; const ok=(c,m)=>{ if(!c){bad++;console.log('FAIL',m);} };
const n=(id,l)=>({id,name:'N'+id,region:'JP',protocol:'VLESS',latencyMs:l});
const list=[n(1,undefined),n(2,80),n(3,-1),n(4,20)]; for(let i=10;i<30;i++) list.push(n(i,100+i));
const s=SceneSheetModel.sortByLatency(list);
ok(s[0].id===4&&s[1].id===2,'sort'); ok(SceneSheetModel.shownPool(s).length===12,'12');
ok(list[0].id===1,'sort does not mutate');
const f=(p)=>({sourceCount:2,poolSize:p,tested:300,reachable:120,underThreshold:40,thresholdMs:300});
ok(SceneSheetModel.lede(true,f(512),3,9).kind===LedeKind.POOL&&SceneSheetModel.lede(true,f(512),3,9).pool===512&&SceneSheetModel.lede(true,f(512),3,9).sources===2,'lede funnel');
ok(SceneSheetModel.lede(false,f(512),3,9).pool===9&&SceneSheetModel.lede(false,f(512),3,9).sources===3,'lede group');
ok(SceneSheetModel.lede(true,f(0),3,0).kind===LedeKind.SOURCES,'lede sources');
ok(SceneSheetModel.lede(false,undefined,0,9).kind===LedeKind.NONE,'lede none');
ok(!SceneSheetModel.showFunnel(false,f(512))&&!SceneSheetModel.showFunnel(true,f(0))&&SceneSheetModel.showFunnel(true,f(1)),'showFunnel');
const st=SceneSheetModel.funnelSteps(f(512)); ok(st.length===4&&st[3].count===40&&SceneSheetModel.funnelTop(st)===512,'steps');
ok(SceneSheetModel.barWidth(512,512)===160&&SceneSheetModel.barWidth(1,512)===12&&SceneSheetModel.barWidth(0,512)===12&&SceneSheetModel.barWidth(5,1)===160,'bar ends');
ok(SceneSheetModel.barWidth(40,512)<SceneSheetModel.barWidth(120,512),'bar mono');
const e=new MockEngine({latencyScale:0}); const set=copySettings(e.settings().value);
set.latencyTtlHours=0; ok(SceneSheetModel.retestHours(set)===24&&SceneSheetModel.funnelMaxAgeMs(set)===3600000,'ttl 0');
set.latencyTtlHours=6; ok(SceneSheetModel.retestHours(set)===6&&SceneSheetModel.funnelMaxAgeMs(set)===6*3600000,'ttl 6');
const ai=e.scenes().value.find(x=>x.kind==='ai'); const video=e.scenes().value.find(x=>x.kind==='video');
ok(SceneSheetModel.closesAfterSource(ai,'auto')&&!SceneSheetModel.closesAfterSource(ai,'subscription_group')&&!SceneSheetModel.closesAfterSource(video,'auto'),'closes');
ok(SceneSheetModel.asksOnFailure(ai)&&!SceneSheetModel.asksOnFailure(video),'asks');
if (ai.exceptions.length>0) ok(SceneSheetModel.pinnedApp(ai,ai.exceptions[0].node)===ai.exceptions[0].app,'pinned');
await e.setSceneSource(video.id,'subscription_group'); ok(!SceneSheetModel.pooled(e.scenes().value.find(x=>x.id===video.id)),'pooled off');
await e.setSceneSource(video.id,'auto'); ok(SceneSheetModel.pooled(e.scenes().value.find(x=>x.id===video.id)),'pooled on');
const fu=await e.nodeFunnel(3600000,300); ok(fu&&fu.poolSize===512&&fu.thresholdMs===300,'mock funnel');
console.log(bad?`scenesheet FAIL ${bad}`:'scenesheet OK'); process.exit(bad?1:0);
