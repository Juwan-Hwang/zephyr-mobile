const { AppNav, BackTo, LibraryDest, NavArgs, ROUTE_NODES, ROUTE_SUBSCRIPTIONS, ROUTE_RULES, ROUTE_SETTINGS, ROUTE_LOGS, ROUTE_LICENSES } = await import('../.out/rt/app/AppNav.ts');
const { GestureLock } = await import('../.out/rt/common/GestureLock.ts');
let bad=0; const ok=(c,m)=>{ if(!c){bad++;console.log('FAIL',m);} };
ok(AppNav.routeOf(LibraryDest.NODES)===ROUTE_NODES,'nodes');
ok(AppNav.routeOf(LibraryDest.SUBSCRIPTIONS)===ROUTE_SUBSCRIPTIONS,'subs');
ok(AppNav.routeOf(LibraryDest.RULES)===ROUTE_RULES,'rules');
ok(AppNav.routeOf(LibraryDest.SETTINGS)===ROUTE_SETTINGS,'settings');
ok(AppNav.routeOf(LibraryDest.SCENES)==='','scenes closes only');
for (const r of [ROUTE_NODES,ROUTE_SUBSCRIPTIONS,ROUTE_RULES,ROUTE_SETTINGS,ROUTE_LOGS,ROUTE_LICENSES]) ok(AppNav.isRoute(r),'route '+r);
ok(!AppNav.isRoute('home')&&!AppNav.isRoute(''),'not route');
ok(AppNav.backOf(new NavArgs(BackTo.LIBRARY))===BackTo.LIBRARY,'backOf');
ok(AppNav.backOf('')===undefined&&AppNav.backOf(undefined)===undefined&&AppNav.backOf(null)===undefined,'backOf other');
ok(AppNav.reopenLibraryAfterPop(BackTo.LIBRARY,true),'reopen');
ok(!AppNav.reopenLibraryAfterPop(BackTo.LIBRARY,false),'not to home');
ok(!AppNav.reopenLibraryAfterPop(BackTo.HOME,true),'from home');
ok(!AppNav.reopenLibraryAfterPop(BackTo.PARENT,true)&&!AppNav.reopenLibraryAfterPop(undefined,true),'parent/undef');
ok(AppNav.shouldPushSubscriptionsForImport('')&&AppNav.shouldPushSubscriptionsForImport(ROUTE_NODES),'push subs');
ok(!AppNav.shouldPushSubscriptionsForImport(ROUTE_SUBSCRIPTIONS),'already subs');
GestureLock.hold(); ok(GestureLock.active(),'held'); GestureLock.release(); ok(GestureLock.active(),'grace');
ok(!GestureLock.active(Date.now()+400),'released after grace');
console.log(bad?'FAILED '+bad:'nav OK'); process.exit(bad?1:0);
