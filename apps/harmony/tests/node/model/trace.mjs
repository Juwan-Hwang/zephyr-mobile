// TraceModel（M1-8 最小版）：覆写选项 / 下标 / 撤销、规则文本、规则测试回退；MockEngine 上覆写往返。
const { TraceModel, TraceResult } = await import('../.out/rt/app/TraceModel.ts');
const { MockEngine } = await import('../.out/rt/engine/MockEngine.ts');
let bad=0; const ok=(c,m)=>{ if(!c){bad++;console.log('FAIL',m);} };
const e=new MockEngine({latencyScale:0}); const scenes=e.scenes().value;
const others=TraceModel.otherScenes(scenes,'ai'); ok(others.length===2&&others.every(s=>s.id!=='ai'),'others');
ok(TraceModel.otherScenes(scenes,undefined).length===2,'others no scene');
ok(TraceModel.selectedIndex(undefined,others)===0&&TraceModel.selectedIndex({target:'unchanged',persistent:false},others)===0,'sel 0');
ok(TraceModel.selectedIndex({target:'direct',persistent:true},others)===1,'sel direct');
ok(TraceModel.selectedIndex({target:'scene',sceneId:others[1].id,persistent:false},others)===3,'sel scene');
ok(TraceModel.selectedIndex({target:'scene',sceneId:'zz',persistent:false},others)===2,'sel scene missing');
const c0=TraceModel.choiceAt(0,others), c1=TraceModel.choiceAt(1,others), c3=TraceModel.choiceAt(3,others);
ok(c0.target==='unchanged'&&c1.target==='direct'&&c3.target==='scene'&&c3.sceneId===others[1].id,'choice');
ok(TraceModel.choiceAt(9,others).target==='direct','choice oob');
const u=TraceModel.undoChoice(undefined); ok(u.target==='unchanged'&&!u.persistent,'undo none');
const u2=TraceModel.undoChoice({target:'direct',persistent:true}); ok(u2.target==='direct'&&u2.persistent,'undo prev');
ok(TraceModel.ruleText('DOMAIN-SUFFIX,claude.ai')==='DOMAIN-SUFFIX, claude.ai','rule text');
const t=await e.connectionTrace('github.com'); ok(t.host==='github.com'&&t.scene==='other','trace github');
await e.overrideHost('github.com','direct',undefined,true); ok((await e.connectionTrace('github.com')).override.target==='direct','override set');
await e.overrideHost('github.com','unchanged',undefined,false); ok((await e.connectionTrace('github.com')).override===undefined,'override cleared');
let threw=false; try{ await e.connectionTrace('example.org'); }catch(x){ threw=true; } ok(threw,'unknown host throws');
const rt=await e.testRule('chat.openai.com'); const f=TraceModel.fromRuleTrace(rt);
ok(f.host===rt.input&&f.rule===rt.rule&&f.connections===0,'fallback '+JSON.stringify({p:rt.policy,s:f.scene}));
if (rt.scene) ok(f.scene===rt.scene.id&&f.node&&f.node.id===rt.scene.selected.id,'fallback scene');
const d=TraceModel.fromRuleTrace({input:'qq.com',isIp:false,rule:'GEOSITE,cn',policy:'DIRECT',tookMicros:1});
ok(d.scene===undefined&&d.node===undefined&&d.exitIp===undefined,'fallback direct');
const r=TraceModel.fromRuleTrace({input:'ads.x',isIp:false,rule:'GEOSITE,ads',policy:'REJECT',tookMicros:1}); ok(r.scene==='REJECT','fallback reject');
ok(new TraceResult(f,false).observed===false,'result');
console.log(bad?`trace FAIL ${bad}`:'trace OK'); process.exit(bad?1:0);
