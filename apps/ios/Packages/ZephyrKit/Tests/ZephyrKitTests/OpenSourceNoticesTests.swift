import XCTest
@testable import ZephyrKit

final class OpenSourceNoticesTests: XCTestCase {
    /// 仓库根：从 apps/ios/Packages/ZephyrKit/Tests/ZephyrKitTests/<本文件> 上溯 7 级。
    private static let repoRoot: URL = {
        var u = URL(fileURLWithPath: #filePath)
        for _ in 0..<7 { u.deleteLastPathComponent() }
        return u
    }()

    private func read(_ name: String) throws -> String {
        try String(contentsOf: Self.repoRoot.appendingPathComponent(name), encoding: .utf8)
    }

    private func repoNotices() throws -> OSSNotices {
        OSSNotices.parse(notices: try read("THIRD_PARTY_NOTICES.md"),
                         licenses: try read("THIRD_PARTY_LICENSES.txt"),
                         appLicense: try read("LICENSE"))
    }

    // MARK: 真实文件（App 打进去的就是这三份）

    /// 依赖表与表头声明的个数一致，且每个依赖都有许可全文或落在“未附许可文件”一节。
    func testRepoFilesParseCompletely() throws {
        let md = try read("THIRD_PARTY_NOTICES.md")
        let n = try repoNotices()
        func declared(_ marker: String) -> Int? {
            guard let r = md.range(of: marker) else { return nil }
            return Int(md[r.upperBound...].prefix { $0.isNumber })
        }
        XCTAssertEqual(n.rust.count, declared("Rust 运行时依赖（core-mobile，"))
        XCTAssertEqual(n.go.count, declared("Go 运行时依赖（mihomo-mobile，"))
        XCTAssertGreaterThan(n.rust.count, 0)
        XCTAssertGreaterThan(n.go.count, 0)
        for c in n.all {
            XCTAssertTrue(!n.licenseTexts(for: c).isEmpty || n.isMissingLicenseFile(c), "\(c.label) 既无全文也不在缺失列表")
        }
        XCTAssertEqual(Set(n.all.map(\.id)).count, n.all.count, "依赖标签重复")
    }

    /// GPL 合规：mihomo 在表内、GPL-3.0 全文可取到、许可口径里的源码地址与版本解析出来。
    func testGPLSourceOffer() throws {
        let n = try repoNotices()
        let mihomo = try XCTUnwrap(n.mihomoComponent)
        XCTAssertTrue(mihomo.license.hasPrefix("GPL-3.0"))
        let gpl = try XCTUnwrap(n.gplText)
        XCTAssertTrue(gpl.contains("GNU GENERAL PUBLIC LICENSE"))
        XCTAssertTrue(gpl.contains("Version 3"))
        XCTAssertEqual(n.mihomo?.url.absoluteString, "https://github.com/MetaCubeX/mihomo")
        XCTAssertEqual(n.mihomo?.version, mihomo.version)
        XCTAssertNotNil(n.goToolchain)
        XCTAssertTrue(n.appLicense.contains("Juwan Hwang"))
    }

    /// 源码仓库地址与 README 的 clone 地址一致（NOTICES：对应源码即本仓库对应的 tag）。
    func testSourceRepositoryMatchesReadme() throws {
        let readme = try read("README.md")
        XCTAssertTrue(readme.contains(OSSNotices.sourceRepository.absoluteString + ".git"))
        XCTAssertEqual(OSSNotices.sourceTags.absoluteString, "https://github.com/Juwan-Hwang/zephyr-mobile/tags")
        XCTAssertTrue(try read("THIRD_PARTY_NOTICES.md").contains("对应源码即本仓库对应的 tag"))
    }

    /// MPL-2.0（uniffi）没有随包许可文件：回落到标准全文。
    func testMissingLicenseFallsBackToStandardText() throws {
        let n = try repoNotices()
        let uniffi = try XCTUnwrap(n.rust.first { $0.name == "uniffi" })
        XCTAssertTrue(n.isMissingLicenseFile(uniffi))
        XCTAssertEqual(n.licenseTexts(for: uniffi).count, 1)
        XCTAssertTrue(n.licenseTexts(for: uniffi)[0].contains("Mozilla Public License"))
    }

    // MARK: 格式细节

    private let sampleNotices = """
    # 第三方许可声明
    - **移动端安装包**静态链接了 [mihomo](https://github.com/MetaCubeX/mihomo) `v1.2.3`（GPL-3.0）。
    - Go 标准库与运行时（go1.27.4）：BSD-3-Clause。

    ## Rust 运行时依赖（core-mobile，3 个）

    | crate | 版本 | 许可（Cargo.toml） | 来源 |
    |---|---|---|---|
    | aead | 0.5.2 | MIT OR Apache-2.0 | crates.io |
    | uniffi | 0.28.3 | MPL-2.0 | crates.io |
    | odd | 1.0.0 | A \\| B | crates.io |

    ## Go 运行时依赖（mihomo-mobile，1 个模块）

    | 模块 | 版本 | 许可 |
    |---|---|---|
    | github.com/metacubex/mihomo | v1.2.3 | GPL-3.0 |
    """

    private var sampleLicenses: String {
        let eq = String(repeating: "=", count: 78), dash = String(repeating: "-", count: 78)
        return [
            "Zephyr Mobile — third-party license texts", "Generated by tools/gen-third-party.sh. Do not edit.", "",
            eq, "Used by: aead 0.5.2 (Rust), github.com/metacubex/mihomo v1.2.3 (Go)", dash, "TEXT ONE", "",
            eq, "Used by: aead 0.5.2 (Rust)", dash, "TEXT TWO",
            eq, "No license file shipped in the package; license per its manifest / repository (standard texts below): uniffi 0.28.3 (Rust)",
            eq, "Standard license text: MPL-2.0", dash, "MPL TEXT", "",
        ].joined(separator: "\n")
    }

    func testParsesTablesAndBlocks() {
        let n = OSSNotices.parse(notices: sampleNotices, licenses: sampleLicenses, appLicense: "  MIT License\n")
        XCTAssertEqual(n.rust.map(\.name), ["aead", "uniffi", "odd"])
        XCTAssertEqual(n.rust[2].license, "A | B")
        XCTAssertEqual(n.go.map(\.label), ["github.com/metacubex/mihomo v1.2.3 (Go)"])
        XCTAssertEqual(n.licenseTexts(for: n.rust[0]), ["TEXT ONE", "TEXT TWO"])
        XCTAssertEqual(n.gplText, "TEXT ONE")
        XCTAssertEqual(n.licenseTexts(for: n.rust[1]), ["MPL TEXT"])
        XCTAssertEqual(n.licenseTexts(for: n.rust[2]), [])
        XCTAssertFalse(n.isMissingLicenseFile(n.rust[2]))
        XCTAssertEqual(n.goToolchain?.version, "go1.27.4")
        XCTAssertEqual(n.goToolchain?.license, "BSD-3-Clause")
        XCTAssertEqual(n.mihomo?.version, "v1.2.3")
        XCTAssertEqual(n.appLicense, "MIT License")
        XCTAssertEqual(n.texts.count, 2, "相同文本只存一份")
    }

    func testSpdxIdentifiers() {
        XCTAssertEqual(OSSNotices.spdxIdentifiers(in: "(MIT OR Apache-2.0) AND Unicode-3.0"), ["MIT", "Apache-2.0", "Unicode-3.0"])
        XCTAssertEqual(OSSNotices.spdxIdentifiers(in: "MIT/Apache-2.0"), ["MIT", "Apache-2.0"])
        XCTAssertTrue(OSSNotices.spdxIdentifiers(in: "MIT（模块包未附许可文件；仓库 LICENSE 为 MIT）").contains("MIT"))
    }

    func testFilter() {
        let n = OSSNotices.parse(notices: sampleNotices, licenses: sampleLicenses)
        XCTAssertEqual(OSSNotices.filter(n.all, query: "  ").count, 4)
        XCTAssertEqual(OSSNotices.filter(n.all, query: "MIHOMO").map(\.name), ["github.com/metacubex/mihomo"])
        XCTAssertEqual(OSSNotices.filter(n.all, query: "mpl").map(\.name), ["uniffi"])
        XCTAssertEqual(OSSNotices.filter(n.all, query: "0.5.2").map(\.name), ["aead"])
    }
}
